const maBaiViet = new URLSearchParams(window.location.search).get("id");
const bai = baiViet[maBaiViet];

const tieuDe = document.getElementById("article-title");
const thongTin = document.getElementById("article-meta");
const anh = document.getElementById("article-image");
const thanBai = document.getElementById("article-body");

if (!bai) {
  document.title = "Không tìm thấy bài viết - NETTO Clothes";
  tieuDe.textContent = "Không tìm thấy bài viết";
  thongTin.textContent = "";
  anh.hidden = true;

  const thongBao = document.createElement("p");
  thongBao.textContent = "Bài viết không tồn tại hoặc đường dẫn không chính xác.";
  thanBai.appendChild(thongBao);
} else {

  document.title = bai.tieuDe + " - NETTO Clothes";
  tieuDe.textContent = bai.tieuDe;
  thongTin.textContent = "👤 " + bai.tacGia + "  |  📅 " + bai.ngayDang;
  anh.src = bai.anh;
  anh.alt = bai.moTaAnh;

  bai.noiDung.forEach(function (doanVan) {
    const p = document.createElement("p");
    p.textContent = doanVan;
    thanBai.appendChild(p);
  });
}
const khuVucBinhLuan = document.getElementById("comments-section");

if (khuVucBinhLuan) {
  khuVucBinhLuan.hidden = !bai;
}

if (bai && khuVucBinhLuan) {
  const formBinhLuan = document.getElementById("comment-form");
  const oTen = document.getElementById("comment-name");
  const oNoiDung = document.getElementById("comment-content");
  const danhSachBinhLuan = document.getElementById("comment-list");
  const thongBaoBinhLuan = document.getElementById("comment-message");
  const khoaLuu = "netto-comments-" + maBaiViet;

  function docBinhLuan() {
    const duLieu = localStorage.getItem(khoaLuu);

    if (!duLieu) {
      return [];
    }

    try {
      const binhLuan = JSON.parse(duLieu);
      return Array.isArray(binhLuan) ? binhLuan : [];
    } catch (loi) {
      console.error("Không đọc được dữ liệu bình luận đã lưu.", loi);
      return [];
    }
  }

  function hienThiBinhLuan() {
    while (danhSachBinhLuan.firstChild) {
      danhSachBinhLuan.removeChild(danhSachBinhLuan.firstChild);
    }

    const binhLuan = docBinhLuan();

    if (binhLuan.length === 0) {
      const rong = document.createElement("p");
      rong.textContent = "Chưa có bình luận nào. Hãy là người bình luận đầu tiên!";
      danhSachBinhLuan.appendChild(rong);
      return;
    }

    binhLuan.forEach(function (muc) {
      const theBinhLuan = document.createElement("article");
      theBinhLuan.className = "comment-item";

      const ten = document.createElement("strong");
      ten.textContent = muc.ten;
      theBinhLuan.appendChild(ten);

      const thoiGian = document.createElement("time");
      thoiGian.dateTime = muc.ngayTao;
      thoiGian.textContent = new Date(muc.ngayTao).toLocaleString("vi-VN");
      theBinhLuan.appendChild(thoiGian);

      const noiDung = document.createElement("p");
      noiDung.textContent = muc.noiDung;
      theBinhLuan.appendChild(noiDung);

      danhSachBinhLuan.appendChild(theBinhLuan);
    });
  }

  formBinhLuan.addEventListener("submit", function (suKien) {
    suKien.preventDefault();

    const ten = oTen.value.trim();
    const noiDung = oNoiDung.value.trim();

    if (!ten || !noiDung) {
      thongBaoBinhLuan.textContent = "Vui lòng nhập tên và nội dung bình luận.";
      return;
    }

    const binhLuan = docBinhLuan();

    binhLuan.unshift({
      ten: ten,
      noiDung: noiDung,
      ngayTao: new Date().toISOString()
    });

    try {
      localStorage.setItem(khoaLuu, JSON.stringify(binhLuan));
    } catch (loi) {
      console.error("Không lưu được bình luận.", loi);
      thongBaoBinhLuan.textContent = "Không lưu được bình luận. Vui lòng thử lại.";
      return;
    }

    formBinhLuan.reset();
    thongBaoBinhLuan.textContent = "Bình luận đã được lưu trên trình duyệt này.";
    hienThiBinhLuan();
  });

  hienThiBinhLuan();
}
